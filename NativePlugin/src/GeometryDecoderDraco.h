#pragma once

#include <IGeometryDecoder.h>

#include<Mesh.h>

#include <mutex>
#include<queue>
#include<thread>

// --------------------------------------------------------------------------
//  Geometry Decoder Class using Google Draco
// --------------------------------------------------------------------------
class GeometryDecoderDraco : public IGeometryDecoder
{


public:

	// --------------------------------------------------------------------------
	// Typedef for draco data
	// --------------------------------------------------------------------------
	typedef std::vector<char> DracoData;
	
	   
	// --------------------------------------------------------------------------
	// Constructor
	// --------------------------------------------------------------------------
	GeometryDecoderDraco();


	//----------------------------------
	// Destructor
	// --------------------------------------------------------------------------
	virtual ~GeometryDecoderDraco();


	// --------------------------------------------------------------------------
	// function to init decoder with frame-by-frame loading
	// --------------------------------------------------------------------------
	bool init(char* filepattern, int start_index, int stop_index);


  	// --------------------------------------------------------------------------
	// Start Decoding
	// --------------------------------------------------------------------------
	bool start_decoding();


	// --------------------------------------------------------------------------
	// Stop Decoding
	// --------------------------------------------------------------------------
	bool stop_decoding();


	// --------------------------------------------------------------------------
	// Get Current Mesh
	// --------------------------------------------------------------------------
	Mesh* get_current_mesh();


	// --------------------------------------------------------------------------
	// Get mesh data for index
	// --------------------------------------------------------------------------
	bool get_mesh_data(int index, Mesh& mesh);
	

	// --------------------------------------------------------------------------
	// Clear frame data
	// --------------------------------------------------------------------------
	void clear_frame_data();


protected:


	// --------------------------------------------------------------------------
	// Decode 
	// --------------------------------------------------------------------------
	bool decode();


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	bool is_buffer_blocked();


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	void update_current_frame();


	// --------------------------------------------------------------------------
	// Stop Decoding
	// --------------------------------------------------------------------------
	bool convert_draco_to_mesh(DracoData & data, Mesh& mesh_out);

private:

	// --------------------------------------------------------------------------
	// All Mesh data which is compressed 
	// --------------------------------------------------------------------------
	std::vector<DracoData> m_encoded_meshes;


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	std::queue<Mesh> m_decoded_meshes;


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	unsigned int m_max_buffer_size;


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	std::thread m_decode_thread;

	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	std::mutex m_geometry_mutex;


	// --------------------------------------------------------------------------
	// 
	// --------------------------------------------------------------------------
	int m_current_frame;

};

