#pragma once


// --------------------------------------------------------------------------
// Basic Decoder Interface
// --------------------------------------------------------------------------
class IDecoder
{

public:

	// --------------------------------------------------------------------------
	// Decoder state 
	enum DecoderState
	{
		INIT_FAIL = -1,
		UNINITIALIZED,
		INITIALIZED,
		DECODING,
		SEEK,
		BUFFERING,
		DECODE_EOF,
		STOP
	};

	// --------------------------------------------------------------------------
	// Constructor 
	// --------------------------------------------------------------------------
	IDecoder():m_initialised(false), m_decoder_state(UNINITIALIZED) {};

	// --------------------------------------------------------------------------
	// Destructor
	// --------------------------------------------------------------------------
	~IDecoder() {};

	// --------------------------------------------------------------------------
	// Stop Decoding
	// --------------------------------------------------------------------------
	virtual bool start_decoding() = 0;

	// --------------------------------------------------------------------------
	// Stop Decoding
	// --------------------------------------------------------------------------
	virtual bool stop_decoding() = 0;

protected:

	// --------------------------------------------------------------------------
	// init flag
	// --------------------------------------------------------------------------
	bool m_initialised;

	// --------------------------------------------------------------------------
	// decoder state flag
	// --------------------------------------------------------------------------
	DecoderState m_decoder_state;

};

